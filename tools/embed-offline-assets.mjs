/**
 * Regenerates offline bundles so Café Core works when opened via file://
 * (browsers block fetch() of local HTML/JSON without a local server).
 *
 * Run: node tools/embed-offline-assets.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const PAGE_FILES = {
    default: 'pages/default.html',
    apps: 'pages/apps.html',
    'find-team': 'pages/find-team.html',
    branding: 'pages/branding.html',
    fuziveer: 'pages/fuziveer.html',
    'black-listed': 'pages/black-listed.html',
    privacy: 'pages/privacy.html',
    terms: 'pages/terms.html',
    notes: 'pages/notes.html',
    bottleneck: 'pages/bottleneck.html',
    sensitivity: 'pages/sensitivity.html',
    edpi: 'pages/edpi.html',
    lineups: 'pages/lineups.html',
    'aim-trainer': 'pages/aim-trainer.html',
};

function toJsString(value) {
    return JSON.stringify(value);
}

function writePageBundle() {
    const entries = Object.entries(PAGE_FILES).map(([key, rel]) => {
        const abs = path.join(root, rel);
        const html = fs.readFileSync(abs, 'utf8').replace(/^\uFEFF/, '');
        return `  ${toJsString(key)}: ${toJsString(html)}`;
    });

    const out = `/* Generated by tools/embed-offline-assets.mjs — do not edit by hand. */
(function () {
  'use strict';
  window.__CAFE_PAGE_HTML__ = Object.freeze({
${entries.join(',\n')}
  });
})();
`;

    const outPath = path.join(root, 'js', 'page-html-bundle.js');
    fs.writeFileSync(outPath, out, 'utf8');
    console.log('Wrote', path.relative(root, outPath));
}

function writeBottleneckPartsJs() {
    const jsonPath = path.join(root, 'data', 'bottleneck-parts.json');
    const data = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
    const out = `/* Generated by tools/embed-offline-assets.mjs — do not edit by hand. */
(function () {
  'use strict';
  const BOTTLENECK_PARTS = ${JSON.stringify(data)};
  window.BOTTLENECK_PARTS = BOTTLENECK_PARTS;
})();
`;
    const outPath = path.join(root, 'data', 'bottleneck-parts.js');
    fs.writeFileSync(outPath, out, 'utf8');
    console.log('Wrote', path.relative(root, outPath));
}

writePageBundle();
writeBottleneckPartsJs();
console.log('Offline assets ready.');
